import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

import { validateScreenManifest } from './manifest-support.mjs';

const root=path.resolve(process.argv[2]||'.');
const manifest=JSON.parse(await readFile(path.join(root,'docs/documentation-system/screen-manifest.json'),'utf8'));
validateScreenManifest(manifest);
const report=JSON.parse(await readFile(path.join(root,'docs/documentation-system/ui-change-report.generated.json'),'utf8'));
const fingerprint=JSON.parse(await readFile(path.join(root,'docs/documentation-system/ui-fingerprint.generated.json'),'utf8'));
const lines=[
  '# Generated Current Interface Baseline',
  '',
  `Source revision: \`${report.sourceRevision}\``,
  '',
  '> This page is generated by the iRespond documentation synchronization service. Interface images are documentation evidence, not signed-device/store certification. Training text must preserve product truth: observations are not automatically verified facts; pledges are not proof of settled money.',
  '',
  '## Registered screens',
  ''
];
for(const screen of manifest.screens){
  const changed=report.changed.includes(screen.id)?' **Changed in this revision.**':'';
  const screenshotEvidence=report.screenshotEvidence?.[screen.id];
  const screenLines=[
    `### ${screen.id}${changed}`,
    '',
    `- Surface: \`${screen.surface||'mobile'}\``,
    `- Route: \`${screen.route}\``,
    `- Source: \`${screen.source}\``,
    `- Source git-blob SHA-1: \`${fingerprint.sources[screen.source]||'unavailable'}\``,
    `- Expected UI anchor: “${screen.expectedText||'none'}”`,
    `- Screenshot target: \`${screen.screenshot}\``,
  ];
  if(screenshotEvidence){
    screenLines.push(
      `- Screenshot evidence: ${screenshotEvidence.status} revision \`${screenshotEvidence.sourceRevision}\` (SHA-256 \`${screenshotEvidence.sha256}\`)`,
      '',
      `![${screen.id} ${screenshotEvidence.status} interface evidence](/${screen.screenshot})`,
      ''
    );
  }else{
    screenLines.push(
      `- Screenshot evidence: unavailable for source revision \`${report.sourceRevision}\``,
      '',
      '_No revision-bound runtime screenshot is available for this source revision._',
      ''
    );
  }
  lines.push(...screenLines);
}

lines.push('## Newly changed or unmapped frontend sources','');
if((report.unmappedFrontendChanges||[]).length){
  lines.push('These files changed inside a canonical frontend root but are not yet assigned to a registered manual screenshot anchor. They must be reviewed before the documentation baseline is accepted.','');
  for(const change of report.unmappedFrontendChanges){
    lines.push(`- **${change.change}** \`${change.source}\` — previous \`${change.previous||'none'}\`, current \`${change.current||'deleted'}\``);
  }
  lines.push('');
}else{
  lines.push('No changed canonical frontend source is currently unmapped.','');
}

const synchronizationContractChanges=report.synchronizationContractChanges||[];
lines.push('## Synchronization contract review','');
if(synchronizationContractChanges.length){
  lines.push('The inputs that govern documentation synchronization changed and require publication review:','');
  for(const change of synchronizationContractChanges){
    lines.push(`- **${change.change}** \`${change.source}\` — previous \`${change.previous||'none'}\`, current \`${change.current||'deleted'}\``);
  }
  lines.push('');
}else{
  lines.push('No screen-manifest, publication-workflow or executable synchronization-tool input changed.','');
}

lines.push('## Runtime capture review','');
if((report.runtimeFailures||[]).length){
  lines.push('Runtime capture requires human review for the following registered surfaces:','');
  for(const failure of report.runtimeFailures){
    lines.push(`- \`${failure.id||failure.route||'unknown'}\`: ${failure.error||failure.anchorWarning||'capture/anchor mismatch'}`);
  }
  lines.push('');
}else{
  lines.push(`Runtime capture available in this run: **${report.runtimeCaptureAvailable?'yes':'no'}**. No captured route or text-anchor mismatch is currently recorded.`,'');
}

const hasAnyChange=(report.frontendSourceChanges||[]).length>0||synchronizationContractChanges.length>0||(report.screenshotChanges||[]).length>0||(report.runtimeFailures||[]).length>0;
lines.push(
  '## Regeneration decision',
  '',
  hasAnyChange
    ? `Manual interface review is required. Registered screen changes: ${report.changed.length?report.changed.map(x=>`\`${x}\``).join(', '):'none'}; changed canonical frontend source files: ${(report.frontendSourceChanges||[]).length}; changed synchronization contract inputs: ${synchronizationContractChanges.length}; unmapped changed sources: ${(report.unmappedFrontendChanges||[]).length}.`
    : 'No canonical frontend source, synchronization-contract input, registered screenshot or runtime-capture review signal changed.',
  ''
);
const dir=path.join(root,'docs/manuals/generated');
await mkdir(dir,{recursive:true});
await writeFile(path.join(dir,'ui-interface-baseline.md'),`${lines.join('\n')}\n`);
console.log(`generated ${path.relative(root,path.join(dir,'ui-interface-baseline.md'))}`);
